package boringyuri.sample.uri

import android.content.UriMatcher
import android.graphics.Rect
import android.net.Uri
import boringyuri.sample.BuildConfig
import boringyuri.sample.data.Address
import org.junit.Assert.assertEquals
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner

/**
 * [ContactUriMatcher] is generated for [ContactUriBuilder] that uses [boringyuri.api.matcher.MatchesTo],
 * so all the matcher codes are generated by the library in [ContactUriMatcher.MatcherCode].
 */
@RunWith(RobolectricTestRunner::class)
class ContactUriMatcherTest {

    private lateinit var baseUri: String
    private lateinit var uriBuilder: ContactUriBuilder
    private lateinit var uriMatcher: ContactUriMatcher

    @Before
    fun setUp() {
        baseUri = "content://boringyuri.sample.provider"
        uriBuilder = ContactUriBuilderImpl()
        uriMatcher = ContactUriMatcher()
    }

    @Test(expected = UnsupportedOperationException::class)
    fun addURI() {
        uriMatcher.addURI("", "", 1)
    }

    @Test
    fun matchContactData() {
        assertEquals(
            ContactUriMatcher.MatcherCode.CONTACT_DATA,
            uriMatcher.match(uriBuilder.buildContactDataUri(42))
        )
    }

    @Test
    fun matchContactData_NotNumericSegment_NoMatch() {
        // `contactId` is a number, so the segment is matched with '#'
        assertEquals(
            UriMatcher.NO_MATCH,
            uriMatcher.match(Uri.parse("$baseUri/data/abc"))
        )
    }

    @Test
    fun matchContactPhoto() {
        assertEquals(
            ContactUriMatcher.MatcherCode.CONTACT_PHOTO,
            uriMatcher.match(uriBuilder.buildContactPhotoUri("friends", 42, Rect(0, 0, 100, 200)))
        )
    }

    @Test
    fun matchContactPhoto_AnyGroupSegment() {
        // `group` is a String, so the segment is matched with '*'
        assertEquals(
            ContactUriMatcher.MatcherCode.CONTACT_PHOTO,
            uriMatcher.match(Uri.parse("$baseUri/file/photo/123/42"))
        )
    }

    @Test
    fun matchVCard() {
        // the matcher code name "vcard" is converted to upper case
        assertEquals(
            ContactUriMatcher.MatcherCode.VCARD,
            uriMatcher.match(uriBuilder.buildVCardUri(42, "John", "Doe", Address("Minsk", "Nemiga")))
        )
    }

    @Test
    fun matchNoPlayServicesVCard() {
        // NO_PLAY_SERVICES is a build config dependant flag, not a constant
        @Suppress("KotlinConstantConditions")
        val expectedMatchCode = if (BuildConfig.NO_PLAY_SERVICES) {
            ContactUriMatcher.MatcherCode.HUAWEI_VCARD
        } else {
            UriMatcher.NO_MATCH
        }

        assertEquals(
            expectedMatchCode,
            uriMatcher.match(uriBuilder.buildNoPlayServicesVCard(42))
        )
    }

    @Test
    fun matchUnknownPath_NoMatch() {
        assertEquals(
            UriMatcher.NO_MATCH,
            uriMatcher.match(Uri.parse("$baseUri/file/unknown/42"))
        )
    }

    @Test
    fun matchUnknownAuthority_NoMatch() {
        assertEquals(
            UriMatcher.NO_MATCH,
            uriMatcher.match(Uri.parse("content://com.example.provider/data/42"))
        )
    }

    @Test
    fun matcherCodes_AreUnique() {
        // the matcher code is generated for disabled Uris as well
        val codes = listOf(
            ContactUriMatcher.MatcherCode.CONTACT_DATA,
            ContactUriMatcher.MatcherCode.CONTACT_PHOTO,
            ContactUriMatcher.MatcherCode.VCARD,
            ContactUriMatcher.MatcherCode.HUAWEI_VCARD,
        )

        assertEquals(codes.size, codes.toSet().size)
    }

    @Test
    fun matcherCodeToString() {
        assertEquals(
            "CONTACT_DATA",
            ContactUriMatcher.MatcherCode.toString(ContactUriMatcher.MatcherCode.CONTACT_DATA)
        )
        assertEquals(
            "CONTACT_PHOTO",
            ContactUriMatcher.MatcherCode.toString(ContactUriMatcher.MatcherCode.CONTACT_PHOTO)
        )
        assertEquals(
            "VCARD",
            ContactUriMatcher.MatcherCode.toString(ContactUriMatcher.MatcherCode.VCARD)
        )
        assertEquals(
            "HUAWEI_VCARD",
            ContactUriMatcher.MatcherCode.toString(ContactUriMatcher.MatcherCode.HUAWEI_VCARD)
        )
    }

    @Test
    fun matcherCodeToString_UnknownCode() {
        assertEquals("-1", ContactUriMatcher.MatcherCode.toString(UriMatcher.NO_MATCH))
    }
}
